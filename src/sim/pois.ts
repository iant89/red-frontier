/**
 * Points of interest and supply drops — GDD §06 (exploration) and §10 (Earth),
 * the content half of TDD §25 T6.
 *
 * Two different things live here, because they arrive differently:
 *
 *  - **Sites** were always on the planet. A wrecked rover, an abandoned survey
 *    camp, a meteorite, an ice cave. `World` scatters them from the seed, so
 *    two colonies on the same seed explore the same planet, and they are there
 *    whether or not anyone ever finds them. The map begins mostly unknown
 *    (GDD §06) — a site is not *on the map* until a rover or the colonist gets
 *    close enough to see it.
 *  - **Supply drops** are scheduled by the simulation, not generated by the
 *    world (GDD §10: "cargo missions arrive at uncertain locations, marked by
 *    transponders"). They land after the mission starts, the transponder
 *    announces them, and dust buries them if nobody comes — a storm buries them
 *    faster, which is the decision the design asks the player to make.
 *
 * Both are one shape, `Poi`, so the renderer, the HUD and the salvage task have
 * exactly one thing to handle. A drop is a `Poi` with `kind: 'supplyDrop'` and a
 * burial countdown; a site has no countdown and never disappears.
 *
 * What a manifest may contain is limited by the economy that exists: bulk
 * resources that ride in a rover's hold and battery cells that land in the
 * grid store. Fluids are deliberately excluded: exposed water and food cargo
 * would freeze, and the current logistics model has no field-fluid recovery.
 *
 * Everything here is pure and seeded. No `Math.random`, no clock, no DOM: the
 * generation is replayable, which is what lets a save regenerate a site it never
 * wrote down and keeps the determinism suites honest.
 */

