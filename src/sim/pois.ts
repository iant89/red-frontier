// ----------------------------------------------------------------- the site ----

export interface Poi {
  id: number;
  kind: PoiKind;
  x: number;
  z: number;
  /** Bulk salvage still lying here, per resource. */
  salvage: Partial<Record<ResourceId, number>>;
  /** Cells still holding charge (kWh). */
  energyKWh: number;
  /**
   * False until a rover or the colonist gets within `POI_DISCOVER_M`.
   * Undiscovered sites are simulated (they are on the planet) but not drawn,
   * not marked and not orderable — GDD §06's "map begins mostly unknown".
   */
  discovered: boolean;
  /** Supply drops only: sols of dust cover left before the cargo is lost. */
  solsToBury: number;
  /** True once the dust won. The container stays on the map as a dead marker. */
  buried: boolean;
  /** The cargo label Earth sent, for the transponder line and the inspector. */
  manifest: string;
}

/** Total bulk salvage left at a site, in kg. */
export function salvageTotalKg(p: Poi): number {
  let total = 0;
  for (const v of Object.values(p.salvage)) total += v;
  return total;
}

/**
 * True when there is nothing left at the site worth sending a rover for.
 *
 * This asks about **bulk salvage only** — what a rover can cut free and carry.
 * Surviving cells are deliberately not part of it: they are handed over by
 * `recoverSiteCells` at the moment the bulk runs out, and gating on them too
 * would mean a container with 60 kWh of cells could never
 * be declared empty, because the cells are only taken once it is.
 */
export function isPickedClean(p: Poi): boolean {
  if (p.kind === 'settlementSite') return true; // a marker, never a job
  return salvageTotalKg(p) <= 0.5;
}

/**
 * How fast a rover cuts salvage free here, in kg per game second. The same
 * weather and drivetrain multipliers that govern mining apply on top of this.
 */
export function salvageRateKgS(kind: PoiKind): number {
  return POI_SALVAGE_RATE_KG_S / (POI_KINDS[kind].workMul ?? 1);
}

/** kg of salvage a rover takes per game second, spread across its contents. */
export function takeSalvage(
  p: Poi,
  roomKg: number,
  rateKgS: number,
  dtS: number,
): { takenKg: number; perResource: Partial<Record<ResourceId, number>> } {
  const want = Math.max(0, Math.min(roomKg, rateKgS * dtS));
  const available = salvageTotalKg(p);
  if (want <= 0 || available <= 0) return { takenKg: 0, perResource: {} };
  const frac = Math.min(1, want / available);
  const perResource: Partial<Record<ResourceId, number>> = {};
  let takenKg = 0;
  for (const [res, amount] of Object.entries(p.salvage)) {
    if (!amount || amount <= 0) continue;
    const take = amount * frac;
    p.salvage[res as ResourceId] = amount - take;
    perResource[res as ResourceId] = take;
    takenKg += take;
  }
  return { takenKg, perResource };
}

/**
 * Build one site. `rng` decides the per-site jitter and which resource mix a
 * generic kind carries, so a seed reproduces its planet exactly.
 */
export function makePoi(
  id: number,
  kind: PoiKind,
  x: number,
  z: number,
  rng: () => number,
): Poi {
  const info = POI_KINDS[kind];
  const jitter = 0.7 + rng() * 0.6; // 0.7× – 1.3×
  const salvage: Partial<Record<ResourceId, number>> = {};
  for (const [res, kg] of Object.entries(info.salvage)) {
    salvage[res as ResourceId] = (kg ?? 0) * jitter;
  }
  return {
    id,
    kind,
    x,
    z,
    salvage,
    energyKWh: (info.energyKWh ?? 0) * jitter,
    discovered: false,
    solsToBury: 0,
    buried: false,
    manifest: '',
  };
}

/**
 * Build one supply drop. Manifest choice and amounts come from `rng`; the
 * burial clock starts at `DROP_BURY_SOLS` and the storm multiplier is applied by
 * the simulation, which is the only thing that knows the sky.
 */
export function makeSupplyDrop(
  id: number,
  x: number,
  z: number,
  rng: () => number,
): Poi {
  const info = ALL_MANIFESTS[Math.min(ALL_MANIFESTS.length - 1, Math.floor(rng() * ALL_MANIFESTS.length))];
  const jitter = 0.75 + rng() * 0.5;
  const salvage: Partial<Record<ResourceId, number>> = {};
  for (const [res, kg] of Object.entries(info.salvage)) {
    salvage[res as ResourceId] = (kg ?? 0) * jitter;
  }
  return {
    id,
    kind: 'supplyDrop',
    x,
    z,
    salvage,
    energyKWh: (info.energyKWh ?? 0) * jitter,
    discovered: true, // the transponder gives the bearing; you still have to look
    solsToBury: DROP_BURY_SOLS,
    buried: false,
    manifest: info.label,
  };
}

// ------------------------------------------------------------ generation ----

/**
 * Weighted kind pick, excluding anything with zero weight (supply drops are
 * scheduled, never scattered). Kept exported because a test pins that every
 * kind the table names is reachable — a zero-weight typo otherwise deletes a
 * feature quietly.
 */
export function pickPoiKind(rng: () => number): PoiKind {
  let total = 0;
  for (const k of ALL_POI_KINDS) total += KIND_WEIGHT[k];
  let roll = rng() * total;
  for (const k of ALL_POI_KINDS) {
    roll -= KIND_WEIGHT[k];
    if (roll <= 0) return k;
  }
  return 'meteorite';
}

/** Kinds the world generator is allowed to scatter. */
export function scatterableKinds(): PoiKind[] {
  return ALL_POI_KINDS.filter((k) => KIND_WEIGHT[k] > 0);
}

/**
 * Where a drop lands: far enough out that recovery is an expedition, close
 * enough in that it is not a fool's errand on a flat battery. GDD §10 wants the
 * location uncertain; the ring makes it a decision rather than a lottery.
 */
export function rollDropRing(rng: () => number, worldHalf: number): { min: number; max: number } {
  const inner = Math.min(worldHalf - 60, Math.max(SPAWN_RADIUS + 120, worldHalf * DROP_RING_INNER_FRAC));
  const outer = Math.max(inner + 60, worldHalf * DROP_RING_OUTER_FRAC);
  return { min: inner, max: outer };
}

/** How fast a drop's burial clock runs under a given storm intensity. */
export function burialRate(stormIntensity: number): number {
  if (stormIntensity <= 0.05) return 1;
  return 1 + (DROP_STORM_BURY_RATE - 1) * Math.min(1, stormIntensity);
}
